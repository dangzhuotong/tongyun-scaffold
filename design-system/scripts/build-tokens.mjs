import {readFileSync, writeFileSync} from 'node:fs';
const root = new URL('../', import.meta.url);
const data = JSON.parse(readFileSync(new URL('tokens/tokens.json', root)));
const block = (selector, values) => `${selector} {\n${Object.entries(values).map(([k,v]) => `  --ty-${k}: ${v};`).join('\n')}\n}\n`;
let css = '/* Generated by scripts/build-tokens.mjs; edit tokens.json. No global theme default. */\n';
css += block(':where([data-ty-theme])', {...data.shared, ...data.components});
for (const [theme, values] of Object.entries(data.themes)) {
 const primitives = Object.fromEntries(Object.entries(values).map(([k,v])=>[`palette-${theme}-${k}`,v]));
 const semantics = Object.fromEntries(Object.keys(values).map(k=>[k,`var(--ty-palette-${theme}-${k})`]));
 css += block(`[data-ty-theme="${theme}"]`, {...primitives, ...semantics});
}
const path = new URL('tokens/tokens.css', root);
if (process.argv.includes('--check')) {
 if (readFileSync(path, 'utf8') !== css) throw new Error('tokens.css is stale; run node scripts/build-tokens.mjs');
} else writeFileSync(path, css);
